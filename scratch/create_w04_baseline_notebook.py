            "# SECTION 1: Baseline Scoring Engine and Reason Code Logic\n",
            "import os\n",
            "import json\n",
            "import pandas as pd\n",
            "import numpy as np\n",
            "\n",
            "# 1. Load starter dataset\n",
            "input_path = \"data/raw/content_refresh_anonymized.csv\"\n",
            "if not os.path.exists(input_path):\n",
            "    raise FileNotFoundError(f\"Starter dataset not found at {input_path}\")\n",
            "\n",
            "df = pd.read_csv(input_path)\n",
            "print(f\"Loaded dataset: {df.shape[0]:,} rows × {df.shape[1]} columns\")\n",
            "\n",
            "# 2. Define non-fitted ranking helper functions\n",
            "def percentile_rank(s: pd.Series) -> pd.Series:\n",
            "    \"\"\"Compute percentile rank in [0, 1], preserving NaNs.\"\"\"\n",
            "    return s.rank(pct=True, na_option='keep')\n",
            "\n",
            "def normalize(s: pd.Series) -> pd.Series:\n",
            "    \"\"\"Min-max normalize a series to [0, 1].\"\"\"\n",
            "    s_min, s_max = s.min(), s.max()\n",
            "    if s_max == s_min:\n",
            "        return pd.Series(0.0, index=s.index)\n",
            "    return (s - s_min) / (s_max - s_min)\n",
            "\n",
            "# 3. Calculate baseline score components\n",
            "df[\"visibility_score\"] = percentile_rank(np.log1p(df[\"impressions_90d\"])).fillna(0.0)\n",
            "df[\"freshness_risk_score\"] = percentile_rank(df[\"days_since_last_update\"]).fillna(0.0)\n",
            "\n",
            "# Position opportunity: reward high rank (position 1-20) weighted by visibility\n",
            "pos_clipped = df[\"avg_position\"].clip(lower=1, upper=50)\n",
            "df[\"position_opportunity_score\"] = (\n",
            "    (1.0 - normalize(pos_clipped))\n",
            "    * df[\"visibility_score\"]\n",
            "    * (df[\"avg_position\"] > 0).astype(float)\n",
            ").fillna(0.0)\n",
            "\n",
            "# Depth gap: reward thin content on visible pages (handled safely with NaNs)\n",
            "word_rank = percentile_rank(df[\"word_count\"])\n",
            "df[\"depth_gap_score\"] = ((1.0 - word_rank) * df[\"visibility_score\"]).fillna(0.0)\n",
            "\n",
            "# Composite Baseline Refresh Score\n",
            "df[\"baseline_refresh_score\"] = (\n",
            "    0.40 * df[\"visibility_score\"]\n",
            "    + 0.30 * df[\"freshness_risk_score\"]\n",
            "    + 0.25 * df[\"position_opportunity_score\"]\n",
            "    + 0.05 * df[\"depth_gap_score\"]\n",
            ").clip(0.0, 1.0)\n",
            "\n",
            "# 4. Reason codes assigner\n",
            "def assign_reason_codes(row: pd.Series) -> list[str]:\n",
            "    reasons = []\n",
            "    if row[\"days_since_last_update\"] >= 180 and row[\"impressions_90d\"] >= 500:\n",
            "        reasons.append(\"stale_visible_page\")\n",
            "    if 0 < row[\"avg_position\"] <= 10 and row[\"content_age_days\"] >= 180:\n",
            "        reasons.append(\"page_one_decay_risk\")\n",
            "    if row[\"impressions_90d\"] >= 500 and 0 < row[\"avg_position\"] <= 20 and row[\"ctr\"] < 0.5:\n",
            "        reasons.append(\"low_ctr_visible_page\")\n",
            "    if 0 < row[\"word_count\"] < 1200 and row[\"impressions_90d\"] >= 250:\n",
            "        reasons.append(\"thin_visible_page\")\n",
            "    if row[\"sessions_90d\"] >= 30 and ((0 < row[\"engagement_rate\"] < 30) or (0 < row[\"scroll_rate\"] < 30)):\n",
            "        reasons.append(\"low_engagement_visible_page\")\n",
            "    if not reasons:\n",
            "        reasons.append(\"general_refresh_review\")\n",
            "    return reasons\n",
            "\n",
            "def assign_suggested_action(reasons_list: list[str]) -> str:\n",
            "    reasons_set = set(reasons_list)\n",
            "    if \"thin_visible_page\" in reasons_set:\n",
            "        return \"expand_and_refresh\"\n",
            "    if \"low_ctr_visible_page\" in reasons_set:\n",
            "        return \"refresh_and_review_ctr\"\n",
            "    if \"stale_visible_page\" in reasons_set or \"page_one_decay_risk\" in reasons_set:\n",
            "        return \"refresh\"\n",
            "    return \"monitor\"\n",
            "\n",
            "raw_reasons = df.apply(assign_reason_codes, axis=1)\n",
            "df[\"reason_codes\"] = raw_reasons.apply(lambda r: \"|\".join(r))\n",
            "df[\"suggested_action_baseline\"] = raw_reasons.apply(assign_suggested_action)\n",
            "\n",
            "# Ground truth label (derived from trend_direction)\n",
            "df[\"is_declining_label\"] = (df[\"trend_direction\"].str.lower() == \"down\").astype(int)\n",
            "\n",
            "# Rank pages (1 = highest priority)\n",
            "df[\"baseline_rank\"] = df[\"baseline_refresh_score\"].rank(method=\"first\", ascending=False).astype(int)\n",
            "df_ranked = df.sort_values(\"baseline_rank\").reset_index(drop=True)\n",
            "\n",
            "print(\"=== SECTION 1 VERIFICATION: BASELINE SCORE COMPUTED ===\")\n",
            "print(f\"Top Score: {df_ranked['baseline_refresh_score'].max():.4f}\")\n",
            "print(f\"Median Score: {df_ranked['baseline_refresh_score'].median():.4f}\")\n",
            "print(f\"Min Score: {df_ranked['baseline_refresh_score'].min():.4f}\")\n"
