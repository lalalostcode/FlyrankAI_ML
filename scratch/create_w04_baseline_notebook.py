            "## 1. My rule and its reason codes\n",
            "\n",
            "### Plain-Language Rule Definition\n",
            "> *\"A page is prioritized for content refresh review if it represents high historical organic visibility/search demand (`impressions_90d`), exhibits age/decay risk due to lack of recent updates (`days_since_last_update`), occupies high-value Page 1/2 Google search real estate (`avg_position` between 1 and 20), or shows thin content depth (`word_count`).\"*\n",
            "\n",
            "### Transparent Scoring Formula\n",
            "We construct a normalized baseline score $S_{\\text{baseline}} \\in [0, 1]$ using four non-fitted heuristic components:\n",
            "\n",
            "$$S_{\\text{baseline}} = 0.40 \\cdot S_{\\text{visibility}} + 0.30 \\cdot S_{\\text{freshness}} + 0.25 \\cdot S_{\\text{position\\_opp}} + 0.05 \\cdot S_{\\text{depth\\_gap}}$$\n",
            "\n",
            "Where:\n",
            "1. **$S_{\\text{visibility}}$**: Percentile rank of log-transformed 90-day impressions ($\\log(1 + \\text{impressions\\_90d})$). High-traffic pages carry greater business impact when declining.\n",
            "2. **$S_{\\text{freshness}}$**: Percentile rank of `days_since_last_update`. Older pages without updates face decay risk.\n",
            "3. **$S_{\\text{position\\_opp}}$**: $(1 - \\text{normalize}(\\text{avg\\_position.clip}(1, 50))) \\times S_{\\text{visibility}} \\times \\mathbf{1}_{(\\text{avg\\_position} > 0)}$. Captures pages on Page 1 or 2 where minor rank drops result in steep traffic loss.\n",
            "4. **$S_{\\text{depth\\_gap}}$**: $(1 - \\text{percentile\\_rank}(\\text{word\\_count})) \\times S_{\\text{visibility}}$ (for pages with valid word counts). Identifies high-exposure pages with shallow content depth.\n",
            "\n",
            "### Reason Codes System\n",
            "To provide actionable decision support to content teams, every page is tagged with one or more diagnostic reason codes:\n",
            "- **`stale_visible_page`**: `days_since_last_update >= 180` AND `impressions_90d >= 500`. (High-traffic page un-updated for 6+ months).\n",
            "- **`page_one_decay_risk`**: `1 <= avg_position <= 10` AND `content_age_days >= 180`. (Top-10 ranking page with high age risk).\n",
            "- **`low_ctr_visible_page`**: `impressions_90d >= 500` AND `1 <= avg_position <= 20` AND `ctr < 0.5%`. (High search visibility but low click-through rate).\n",
            "- **`thin_visible_page`**: `0 < word_count < 1200` AND `impressions_90d >= 250`. (Shallow content volume despite measurable search interest).\n",
            "- **`low_engagement_visible_page`**: `sessions_90d >= 30` AND (`0 < engagement_rate < 30%` OR `0 < scroll_rate < 30%`). (Decent user traffic but weak page engagement).\n",
            "- **`general_refresh_review`**: Default catch-all tag when no specific high-risk threshold is crossed.\n",
            "\n",
            "### Suggested Actions Hierarchy\n",
            "- **`expand_and_refresh`**: Assigned if `thin_visible_page` is present.\n",
